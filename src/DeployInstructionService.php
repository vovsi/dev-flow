<?php

declare(strict_types=1);

namespace App;

/** Оркестрирует форматирование инструкции выливки в описание PR по стандарту команды и зовёт нейронку через LlmClientInterface */
final class DeployInstructionService
{
    private const SYSTEM_PROMPT = <<<'PROMPT'
Мне нужно чтобы ты составил описание для PR в GitHub. Далее идёт инструкция — этот текст нужно
привести в порядок: он должен быть понятным разработчику, чётко излагать суть при этом максимально
кратко (по делу, без воды). Главное — оформи читабельно. Если в самой инструкции встречаются
конкретные названия переменных/таблиц/баз/SQL-запросов/конфигов — выдели их стилистически (например
через inline-код), но только те, что реально есть в тексте — не придумывай и не добавляй свои. Ни в
коем случае не изменяй смысл текста инструкции (!) — оставляй его таким же по содержанию, каким он
дан. Инструкция не должна содержать ничего лишнего, чего в ней не было по сути — ни выдуманных
названий, ни выдуманных деталей, ни дополнений от себя.

Отдельное строгое правило про код: всё, что похоже на код или технический идентификатор —
SQL-запросы, названия таблиц/колонок/баз/переменных/конфигов, куски кода на английском — нужно
скопировать символ-в-символ ровно так, как дано в инструкции, без единого изменения. Нельзя
переписывать, «улучшать», переформатировать, дополнять, сокращать, менять регистр, комментарии,
переносы строк или порядок внутри такого фрагмента — и нельзя сочинять свой код или запрос вместо
данного, даже если кажется, что так понятнее. С таким фрагментом разрешено только одно — обернуть
его как есть в оформление (inline-код или блок кода тройными обратными кавычками ```sql/```
и т.п., без изменения содержимого). Всё остальное — обычный текст вокруг кода — можно свободно
переформулировать, менять порядок слов и стиль, как и весь остальной текст инструкции.

Важно: результат увидит не тот, кто написал тебе эту инструкцию, а другой человек — ревьювер,
который будет читать готовое описание PR на GitHub. Поэтому в тексте не должно быть ничего,
адресованного тебе или автору инструкции (никаких «вот отформатированный текст», «я оформил как
попросили», пояснений что и почему было изменено, вопросов, комментариев о процессе форматирования
и т.п.) — только сам текст, который должен увидеть ревьювер.

Вставь получившийся текст вместо <инструкция> в шаблон ниже и верни результат целиком, СТРОГО
скопировав первые две строки шаблона символ-в-символ (включая эмодзи и Markdown-разметку — не
убирай и не меняй их, эмодзи ❗ здесь вместо цветного текста, потому что GitHub вырезает inline-стили
из описания PR и цвет через HTML там не работает, а эмодзи рендерится красным нативно) — больше
ничего не пиши, никаких пояснений до или после:

### ❗ **ВАЖНО** ❗
**Перед мерджем сделать следующее:**
<инструкция>
PROMPT;

    public function __construct(
        private readonly LlmClientInterface $llmClient,
    ) {
    }

    public function generate(string $instruction): string
    {
        return $this->llmClient->chat(self::SYSTEM_PROMPT, $instruction);
    }

    /**
     * Та же инструкция, но собранная из введённых по отдельности частей — что сделать с базой,
     * что с конфигами и что ещё важно (шаг «Закоммитить изменения»). Подписи нужны самой
     * нейронке: без них склеенные абзацы читаются как один список шагов, и оформленный блок
     * теряет разделение. Пустая часть в текст не попадает вовсе.
     */
    public function generateFromParts(string $database, string $config, string $other = ''): string
    {
        $parts = [];
        foreach (['База данных' => $database, 'Конфиги' => $config, 'Другое' => $other] as $title => $text) {
            if (trim($text) !== '') {
                $parts[] = "{$title}:\n" . trim($text);
            }
        }

        return $this->generate(implode("\n\n", $parts));
    }
}
